/**
 * Writes data/glimmer-switch.json, the committed record /dashboard/evals shows on any server (the raw reads and
 * .data/ stay local): the v1 switch test's result computed from the reads files with the app's own judging
 * (evaluateReads), the real printed serials split into readable and covered views, the row ids v1 scored
 * (v2 may never be scored on them), and the v2 rule as pre-registered.
 *
 *   npx tsx scripts/glimmer-switch-summary.ts --data .data/finetune/glimmer-2026-10-29.jsonl --adapter-name rw-labels-2026-10-29
 */
import fs from "node:fs";
import { decideSwitch, evaluateReads, MIN_TRAIN_ROWS, SWITCH_RULE_V2_TEXT, type TrainingLine } from "../lib/learning/glimmer-eval";
import { REAL_SHEET_SERIALS } from "../lib/learning/label-set";
import { isTrustedRead, LABEL_CONFIDENCE_FLOOR } from "../lib/openweights/glimmer";
import type { ReadRecord } from "../lib/openweights/glimmer-modal";

const arg = (n: string) => {
  const i = process.argv.indexOf(`--${n}`);
  return i > 0 ? process.argv[i + 1] : undefined;
};
const data = arg("data");
const adapterName = arg("adapter-name");
if (!data || !adapterName) throw new Error("usage: --data <f.jsonl> --adapter-name <name>");
const stem = data.replace(/\.jsonl$/, "");
const lines = fs.readFileSync(data, "utf8").trim().split("\n").map((l) => JSON.parse(l) as TrainingLine);
const held = lines.filter((l) => l.meta.split === "heldout");
const metas = held.map((l) => l.meta);
const baseReads = JSON.parse(fs.readFileSync(`${stem}.reads.base.json`, "utf8")) as ReadRecord[];
const adapterReads = JSON.parse(fs.readFileSync(`${stem}.reads.${adapterName}.json`, "utf8")) as ReadRecord[];
const b = evaluateReads(metas, baseReads);
const a = evaluateReads(metas, adapterReads);
const d = decideSwitch(b, a, { trainRows: lines.length - held.length, adapterName });

const real = new Set<string>(REAL_SHEET_SERIALS);
const realViews = metas.filter((m) => m.source === "sheet" && m.labelId && real.has(m.labelId));
const trusted = (r: ReadRecord | undefined) => Boolean(r?.read && isTrustedRead(r.read, LABEL_CONFIDENCE_FLOOR) && r.read.serialRead?.trim());
const jB = new Map(b.judgements.map((j) => [j.rowId, j] as const));
const jA = new Map(a.judgements.map((j) => [j.rowId, j] as const));
const rB = new Map(baseReads.map((r) => [r.rowId, r] as const));
const rA = new Map(adapterReads.map((r) => [r.rowId, r] as const));
const readable = realViews.filter((m) => !m.truth.serialUnreadable);
const covered = realViews.filter((m) => m.truth.serialUnreadable);
const perSerial = REAL_SHEET_SERIALS.map((s) => {
  const rd = readable.filter((m) => m.labelId === s);
  const cv = covered.filter((m) => m.labelId === s);
  return { serial: s, readable: { views: rd.length, base: rd.filter((m) => jB.get(m.rowId)?.serialExact).length, adapter: rd.filter((m) => jA.get(m.rowId)?.serialExact).length }, covered: { views: cv.length, baseTrusted: cv.filter((m) => trusted(rB.get(m.rowId))).length, adapterTrusted: cv.filter((m) => trusted(rA.get(m.rowId))).length } };
});

const out = {
  note: "Generated by scripts/glimmer-switch-summary.ts from the live held-out reads (judged by lib/learning/glimmer-eval.ts). The raw reads stay in .data/.",
  v1: {
    ranAt: "2026-10-29",
    adapter: adapterName,
    reads: "live through the served FP8 endpoint (base vs LoRA)",
    rule: "v1: at least +5 points AND +2 rows of exact-serial match over the base, no more false clears, at least 20 shared held-out rows, at least 50 trained on (registered before the run)",
    heldoutRows: metas.length,
    trainRows: lines.length - held.length,
    base: { exactSerial: b.exactSerial, falseClears: b.falseClears.total, skuMatch: b.skuMatch, skuRows: b.skuRows },
    adapterMetrics: { exactSerial: a.exactSerial, falseClears: a.falseClears.total, skuMatch: a.skuMatch, skuRows: a.skuRows },
    useAdapter: d.useAdapter,
    failed: d.failed,
    ceilingFlaw: `with the base at ${b.exactSerial}/${metas.length}, +5 points needs at least ${Math.ceil((b.exactSerialRate + 0.05) * metas.length * 1000) / 1000} of ${metas.length}, so only a perfect ${metas.length}/${metas.length} could pass; the verdict stands, the rule is replaced by v2 for future runs`,
    realPrintedSerials: {
      views: realViews.length,
      readable: { views: readable.length, base: readable.filter((m) => jB.get(m.rowId)?.serialExact).length, adapter: readable.filter((m) => jA.get(m.rowId)?.serialExact).length },
      covered: { views: covered.length, baseTrusted: covered.filter((m) => trusted(rB.get(m.rowId))).length, baseFalseClears: covered.filter((m) => jB.get(m.rowId)?.falseClear).length, adapterTrusted: covered.filter((m) => trusted(rA.get(m.rowId))).length, adapterAbstained: covered.filter((m) => !trusted(rA.get(m.rowId))).length },
      perSerial,
    },
    scoredRowIds: metas.map((m) => m.rowId).sort(),
  },
  v2: { rule: SWITCH_RULE_V2_TEXT, minTrainRows: MIN_TRAIN_ROWS, preregisteredAt: "before any bench clip existed", status: "pre-registered, not yet run: scored only on rows not in v1.scoredRowIds (the d1–d3 bench crops once the bench clips are filmed, plus freshly seeded rows)" },
};
fs.writeFileSync("data/glimmer-switch.json", `${JSON.stringify(out, null, 1)}\n`);
console.log(JSON.stringify({ v1: { ...out.v1, scoredRowIds: `${out.v1.scoredRowIds.length} ids` } }, null, 1));
